/**
 * Standard welcome console message utility for craft projects.
 * @param {string} siteName - The name of the craft site (e.g. "EnvelopesCraft").
 * @param {string} contactEmail - The contact email address (e.g. "info@envelopes-craft.com").
 */
function logWelcomeMessage(siteName, contactEmail) {
    console.log(`
🎨 Welcome to ${siteName} Website!
✨ Built with love using HTML, CSS, JavaScript & Bootstrap
🚀 Featuring smooth scrolling and animations
📧 Contact: ${contactEmail}

Made with ❤️ by the ${siteName} team
`);
}
